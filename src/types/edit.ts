/**
 * Non-destructive editing model.
 *
 * The source video is never modified. Every effect is stored here as an
 * instruction, saved as JSON in SQLite (project_edits table), and the final
 * MP4 is rendered from these instructions.
 *
 * All times are in SECONDS on the SOURCE video's timeline unless a field is
 * explicitly named `output...`. Freeze frames REPLACE a stretch of video and
 * the original audio keeps playing, so output time == source time (see
 * buildTimeline in services/timeline/editTimeline.ts).
 */

export const EDIT_CONFIG_VERSION = 1;

/** Where an effect came from. Unapply Default removes only "default". */
export type EffectOrigin = "default" | "custom";

/** Subtle transitions supported by the FFmpeg `xfade` filter we ship. */
export type TransitionKind =
  | "dissolve" // random-pixel dissolve (FFmpeg xfade "dissolve")
  | "fade" // smooth crossfade
  | "fadeblack"
  | "slideleft"
  | "slideright"
  | "wipe" // image wipe
  | "checkerboard" // custom expression
  | "snowdrift" // custom expression
  | "pixelize" // "Reconfigure pixel"
  | "elastic"; // "Elastic wrap" (squeeze)

/** A contiguous, in-order piece of the source video. */
export interface Segment {
  id: string;
  start: number;
  end: number;
}

/**
 * A transition at a cut point. `at` is a source time, not a segment index,
 * so custom transitions stay valid when default segments are regenerated.
 */
export interface TransitionEffect {
  id: string;
  origin: EffectOrigin;
  at: number;
  kind: TransitionKind;
  duration: number;
}

export type ZoomDirection =
  | "center"
  | "top-left"
  | "top-right"
  | "bottom-left"
  | "bottom-right";

/**
 * Replace the video from `sourceTime` to `sourceTime + duration` with the
 * frame at `sourceTime`, zooming from `zoomFrom` to `zoomTo` (1 = no zoom).
 * The original frames in that stretch are dropped; the ORIGINAL AUDIO KEEPS
 * PLAYING, and the output length does not change.
 */
export interface FreezeEffect {
  id: string;
  origin: EffectOrigin;
  sourceTime: number;
  duration: number;
  zoomFrom: number;
  zoomTo: number;
  zoomDirection: ZoomDirection;
}

/**
 * A blurred area. Position and size are fractions of the video frame (0–1)
 * so they survive any output resolution. Times are source times.
 * Blur is always user-created; nothing is blurred automatically.
 */
export interface BlurRegion {
  id: string;
  start: number;
  end: number;
  x: number;
  y: number;
  width: number;
  height: number;
  /** 1 (light) to 10 (strong). */
  intensity: number;
  shape: "rectangle" | "ellipse";
}

/** Everything generated by Apply Default, kept together so Unapply is exact. */
export interface DefaultEdit {
  /**
   * "standard" = the built-in random Default; "mine" = generated from the
   * user's My Default preset. Missing on edits saved before presets existed.
   */
  source?: "standard" | "mine";
  /** Seed for the generator: the same seed always rebuilds the same edit. */
  seed: number;
  generatedAt: string;
  segments: Segment[];
  transitions: TransitionEffect[];
  freezes: FreezeEffect[];
}

export interface AudioSettings {
  /** Burmese voice volume, 0–2 (1 = unchanged). */
  dubVolume: number;
  /** Original audio volume, 0–2. */
  originalVolume: number;
  /** Lower the original audio while the Burmese voice speaks. */
  duckOriginal: boolean;
}

export interface SubtitleSettings {
  /** CC toggle on the Edit page preview. */
  showInPreview: boolean;
  /** Draw subtitles into the exported video. */
  burnIn: boolean;
}

export interface EditConfig {
  version: typeof EDIT_CONFIG_VERSION;
  /** The video this edit applies to (the project's original). */
  sourceUri: string;
  sourceDuration: number;
  defaultEdit: DefaultEdit | null;
  custom: {
    transitions: TransitionEffect[];
    freezes: FreezeEffect[];
    blurs: BlurRegion[];
  };
  audio: AudioSettings;
  subtitles: SubtitleSettings;
  updatedAt: string;
}

/** One playable piece of the output video, in output order. */
export type TimelineItem =
  | {
      type: "clip";
      sourceStart: number;
      sourceEnd: number;
      outputStart: number;
      outputEnd: number;
    }
  | {
      type: "freeze";
      freeze: FreezeEffect;
      /** The source stretch this freeze replaces (audio plays through it). */
      sourceStart: number;
      sourceEnd: number;
      outputStart: number;
      outputEnd: number;
    };

/** A cut between two output items, with the transition to render there. */
export interface TimelineCut {
  sourceTime: number;
  /** Index into Timeline.items of the item just before the cut. */
  afterItemIndex: number;
  transition: TransitionEffect | null;
}

/** The resolved timeline: what the renderer and preview both follow. */
export interface Timeline {
  items: TimelineItem[];
  cuts: TimelineCut[];
  outputDuration: number;
}

/**
 * The user's own reusable default ("My Default"), stored once for the whole
 * app. Positions are SECONDS.
 *
 * - repeat ON: the lines describe ONE ROUND of `patternLength` seconds, and
 *   the round repeats until the video ends (0:05, 0:10, 0:15 in a 0:50
 *   round -> 0:05 0:10 0:15 | 0:55 1:00 1:05 | ...).
 * - repeat OFF: the lines are exact times on the video, applied once; lines
 *   after the end of a shorter video are skipped.
 */
export interface MyDefaultPreset {
  version: 2;
  repeat: boolean;
  /** Length of one round (seconds). Used when `repeat` is on. */
  patternLength: number;
  transitions: {
    /** Seconds from the start of the round (repeat) or of the video. */
    at: number;
    kind: TransitionKind;
    duration: number;
  }[];
  freezes: {
    at: number;
    duration: number;
    zoomTo: number;
    zoomDirection: ZoomDirection;
  }[];
  updatedAt: string;
}
